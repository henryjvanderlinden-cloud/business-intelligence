"""Build the schema viewer: one self-contained HTML page from model/ and the analysis record's catalogue.

The viewer asked for by the author on 2026-10-29 (ARC-OP-29; handover 11). It is a reader, never a source of truth
(142 section 3): everything it shows is read from the declaration files and the catalogue evidence on each build, and
nothing in it is edited by hand. Run from the repository root:

    python prototypes/schema_viewer/build.py

Writes prototypes/schema_viewer/out/schema_viewer.html (a complete page, to open by double-click) and
prototypes/schema_viewer/out/fragment.html (the same page without its document wrapper). Standard library only.

For a source that has no model yet, such as a client's database after the catalogue pass
(prototypes/catalogue_pass/), draw its raw source layer alone, from the newest catalogue evidence of each table:

    python <nsdn>/prototypes/schema_viewer/build.py --root . --source <code> [--source <code>] --out <folder>
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import model_lib as ml  # noqa: E402

GEN_NOTE = "generated by rule, not declared (model/README.md section 5); names illustrative until the generator exists"


def col(n, t, role="", note="", gen=False, flags=None):
    return {"n": n, "t": t, "r": role, "note": note, "g": gen, "f": flags or {}}


def latest_catalogues(root, source):
    """{'schema.table': (catalogue, path)} from the newest catalogue evidence of each table of one source."""
    out = {}
    base = os.path.join(root, "analysis", source, "tables")
    for dirpath, dirnames, filenames in os.walk(base):
        if os.path.basename(dirpath) != "evidence":
            continue
        best = None
        for fn in sorted(filenames):
            if not fn.endswith(".json"):
                continue
            with open(os.path.join(dirpath, fn), encoding="utf-8") as f:
                d = json.load(f)
            if d.get("kind") == "catalogue query" and isinstance(d.get("result"), dict) and "columns" in d["result"]:
                if best is None or d.get("ran_at", "") > best[0]:
                    best = (d.get("ran_at", ""), os.path.relpath(os.path.join(dirpath, fn), root))
        if best:
            cat = ml.catalogue(root, best[1])
            t = cat["table"][0]
            out["%s.%s" % (t["schema_name"], t["table_name"])] = (cat, best[1])
    return out


def main():
    ap = argparse.ArgumentParser(description="Build the schema viewer.")
    ap.add_argument("--root", default=ROOT, help="repository holding analysis/ and model/ (default: this repository)")
    ap.add_argument("--source", action="append", default=[],
                    help="draw this source's raw layer from its catalogue evidence alone (repeatable)")
    ap.add_argument("--out", default=os.path.join(HERE, "out"), help="folder for the generated pages")
    ap.add_argument("--title", default="", help="name shown on the page (default: from the sources)")
    args = ap.parse_args()
    root = os.path.abspath(args.root)
    decls = ml.load(root) if not args.source else []
    by_name = {f["name"]: (r, f, s, p) for r, f, s, p, e in decls}
    src = [d for d in decls if d[1].get("kind") == "source"]
    cats, table_info = {}, {}
    for code in args.source:
        for table, (cat, path) in sorted(latest_catalogues(root, code).items()):
            cats[table] = cat
            kind = (cat["table"][0].get("table_kind") or "table")
            table_info[table] = {"catalogue": path, "source": code, "kind": "view" if "view" in kind else "table"}
    for rel, front, sections, prose, errs in src:
        for table, flags in sections["Base tables"]:
            cats[table] = ml.catalogue(root, flags["catalogue"])
            table_info[table] = flags
            hist = flags.get("history", "none")
            if hist != "none":
                hpath = flags["catalogue"].replace(table.split(".")[1] + "/", hist.split(".")[1] + "/", 1)
                hdir = os.path.dirname(os.path.join(root, hpath))
                for fn in sorted(os.listdir(hdir)):
                    with open(os.path.join(hdir, fn), encoding="utf-8") as f:
                        d = json.load(f)
                    if d.get("kind") == "catalogue query" and "columns" in d.get("result", {}):
                        cats[hist] = ml.catalogue(root, os.path.relpath(os.path.join(hdir, fn), root))
                        table_info[hist] = {"history_of": table}
                        break

    def srctype(qual):
        t, c = qual.rsplit(".", 1)
        for x in cats.get(t, {"columns": []})["columns"]:
            if x["column_name"] == c:
                return ml.type_text(x) + ("" if x["is_nullable"] == "1" else " not null")
        return "?"

    nodes, edges = [], []
    feeds = {}   # source table -> [vault names]

    def feed(table, name):
        feeds.setdefault(table, [])
        if name not in feeds[table]:
            feeds[table].append(name)

    def meta(front, rel):
        keep = ["status", "ruled_in", "defined_in", "subject_area", "concept", "grain", "label", "driving", "optional",
                "optional_note", "effectivity", "effectivity_start", "source_table", "parent_key", "satellite_kind",
                "split_reason", "valid_time", "class", "class_condition", "key", "key_space", "history",
                "written_by", "written_at", "step"]
        m = {k: front[k] for k in keep if k in front}
        m["file"] = rel
        return m

    hubs = [d for d in decls if d[1].get("kind") == "hub"]
    links = [d for d in decls if d[1].get("kind") == "link"]
    sats = [d for d in decls if d[1].get("kind") == "satellite"]
    refs = [d for d in decls if d[1].get("kind") == "reference"]

    for rel, f, s, p, e in hubs:
        n = f["name"]
        h = n[4:]
        cols = [col("hk_" + h, "hash", "PK", "hash of key space and business key (ADR-0030)", True)]
        for subj, fl in s["Business key"]:
            cols.append(col(subj.split(".")[-1], srctype(subj), "BK", "key space %s, %s" % (fl["key_space"], fl["key_kind"])))
            feed(subj.rsplit(".", 1)[0], n)
        cols += [col("load_ts", "timestamp", "", "knowledge time", True), col("record_source", "text", "", "", True)]
        nodes.append({"id": n, "layer": "vault", "kind": "hub", "area": f["subject_area"], "cols": cols,
                      "meta": meta(f, rel), "ev": [x[0] for x in s.get("Evidence", [])], "notes": p})
        nodes.append({"id": "sat_%s__wwi__audit" % h, "layer": "vault", "kind": "audit", "area": f["subject_area"],
                      "parent": n, "gen": True,
                      "cols": [col("hk_" + h, "hash", "PK FK", "", True), col("load_ts", "timestamp", "PK", "", True),
                               col("source_version", "text", "PK", "record source and source system time (149 Rule 2)", True),
                               col("LastEditedBy", "int", "", "the source's audit column (149 Rule 3)", True),
                               col("source_system_ts", "timestamp", "", "ValidFrom or LastEditedWhen", True)],
                      "meta": {"note": GEN_NOTE, "rule": "149 Rule 3: the source's version log"}})
        nodes.append({"id": "sts_%s__wwi" % h, "layer": "vault", "kind": "status", "area": f["subject_area"],
                      "parent": n, "gen": True,
                      "cols": [col("hk_" + h, "hash", "PK FK", "", True), col("load_ts", "timestamp", "PK", "", True),
                               col("status", "text", "", "present, absent-unresolved, deletion-confirmed, reappeared", True),
                               col("record_source", "text", "", "", True)],
                      "meta": {"note": GEN_NOTE, "rule": "149 Rule 7: status tracking between complete extracts"}})
        edges.append(["sat_%s__wwi__audit" % h, n, "sat"])
        edges.append(["sts_%s__wwi" % h, n, "sat"])

    for rel, f, s, p, e in links:
        n = f["name"]
        a, b = f["from"], f["to"]
        role = n.split("__", 1)[1]
        ka = "hk_" + a[4:]
        kb = "hk_" + b[4:] if a != b else "hk_" + role
        cols = [col("hk_" + n[4:], "hash", "PK", "hash of the business keys joined (ADR-0030)", True),
                col(ka, "hash", "FK", "driving" if f["driving"] != "none" else "", True),
                col(kb, "hash", "FK", "", True),
                col("load_ts", "timestamp", "", "knowledge time", True), col("record_source", "text", "", "", True)]
        srccols = [x for x in s.get("Columns", [])]
        start = next((fl.get("effectivity_start", "") for subj, fl in srccols if fl.get("end") == "from"), "")
        f = dict(f, effectivity_start=start)
        for subj, fl in srccols:
            feed(subj.split(" + ")[0].rsplit(".", 1)[0], n)
        nodes.append({"id": n, "layer": "vault", "kind": "link", "area": f["subject_area"], "cols": cols,
                      "src": [{"n": subj, "t": srctype(subj), "f": fl} for subj, fl in srccols],
                      "meta": meta(f, rel), "ev": [x[0] for x in s.get("Evidence", [])], "notes": p,
                      "ends": [a, b]})
        edges.append([n, a, "from"])
        edges.append([n, b, "to"])
        eff = "eff_%s__wwi" % n[4:]
        ecols = [col("hk_" + n[4:], "hash", "PK FK", "", True), col(ka, "hash", "", "driving key" if f["driving"] != "none" else "", True),
                 col("load_ts", "timestamp", "PK", "", True), col("effective_from", "timestamp", "", "start: " + f["effectivity_start"], True),
                 col("effective_to", "timestamp", "", "end, by driving key", True)]
        for subj, fl in srccols:
            if "kept" in fl:
                ecols.append(col(subj.split(".")[-1], srctype(subj), "", "kept as delivered (149 section 4)"))
        nodes.append({"id": eff, "layer": "vault", "kind": "effectivity", "area": f["subject_area"], "parent": n,
                      "gen": True, "cols": ecols,
                      "meta": {"note": GEN_NOTE, "rule": "149 Rule 6: driving-key effectivity",
                               "effectivity": f["effectivity"], "effectivity_start": f["effectivity_start"]}})
        edges.append([eff, n, "sat"])

    for rel, f, s, p, e in sats:
        n = f["name"]
        par = f["parent"]
        cols = [col("hk_" + par[4:], "hash", "PK FK", "", True), col("load_ts", "timestamp", "PK", "knowledge time", True),
                col("source_version", "text", "PK", "149 Rule 2", True),
                col("valid_from", "timestamp", "", "business valid time: " + f["valid_time"], True),
                col("source_system_ts", "timestamp", "", "labelled, never business time", True),
                col("hash_diff", "hash", "", "change detection on payload and valid time", True)]
        for subj, fl in s["Columns"]:
            role = ""
            if "reading_key" in fl:
                role = "PK"
            note = "; ".join("%s=%s" % kv for kv in fl.items())
            cols.append(col(subj, srctype(f["source_table"] + "." + subj), role, note, False, fl))
            if "code" in fl:
                edges.append([n, fl["code"], "code"])
        feed(f["source_table"], n)
        nodes.append({"id": n, "layer": "vault", "kind": "satellite", "area": f["subject_area"], "parent": par,
                      "cols": cols, "meta": meta(f, rel), "ev": [x[0] for x in s.get("Evidence", [])], "notes": p})
        edges.append([n, par, "sat"])

    for rel, f, s, p, e in refs:
        n = f["name"]
        k = f["key"]
        cols = [col(k.split(".")[-1], srctype(k), "PK", "code, key space %s" % f["key_space"])]
        cols += [col(subj, srctype(f["source_table"] + "." + subj), "", "") for subj, fl in s["Columns"]]
        cols += [col("source_system_ts", "timestamp", "PK", "every version (149 Rule 8)", True),
                 col("load_ts", "timestamp", "", "", True)]
        feed(f["source_table"], n)
        nodes.append({"id": n, "layer": "vault", "kind": "reference", "area": "reference", "cols": cols,
                      "meta": meta(f, rel), "ev": [x[0] for x in s.get("Evidence", [])], "notes": p})

    # The raw source layer: every table of the catalogue, its keys and foreign keys.
    for table, cat in sorted(cats.items()):
        info = table_info[table]
        pk = set()
        for k in cat["keys"]:
            if str(k.get("is_primary_key", "")) in ("1", "True", "true"):
                pk.add(k.get("column_name"))
        fks = {}
        for fk in cat["fks_out"]:
            fks[fk.get("column_name") or fk.get("parent_column")] = "%s.%s.%s" % (
                fk.get("referenced_schema") or fk.get("ref_schema", ""), fk.get("referenced_table") or fk.get("ref_table", ""),
                fk.get("referenced_column") or fk.get("ref_column", ""))
        cols = []
        for c in cat["columns"]:
            nm = c["column_name"]
            role = " ".join(x for x in ("PK" if nm in pk else "", "FK" if nm in fks else "") if x)
            note = ("→ " + fks[nm]) if nm in fks else ""
            cols.append({"n": nm, "t": ml.type_text(c) + ("" if c["is_nullable"] == "1" else " not null"), "r": role,
                         "note": note, "d": c.get("description", ""), "g": False, "f": {}})
        sch = table.split(".")[0]
        kind = "history" if "history_of" in info else info.get("kind", "table")
        nodes.append({"id": table, "layer": "source", "kind": kind,
                      "area": sch, "cols": cols, "parent": info.get("history_of"),
                      "meta": {"description": (cat["table"] or [{}])[0].get("description", ""), "schema": sch,
                               "system_time": info.get("system_time", ""), "audit": info.get("audit", ""),
                               "history": info.get("history", info.get("history_of", "")),
                               "catalogue": info.get("catalogue", ""),
                               "estimated_rows": est if (est := str((cat["table"] or [{}])[0].get("estimated_rows", ""))) not in ("-1", "") else "",
                               "triggers": ", ".join(x.get("trigger_name", "") for x in cat.get("triggers", []))},
                      "feeds": feeds.get(table, []),
                      "reads": ["%s.%s" % (r["ref_schema"], r["ref_table"]) for r in cat.get("view_reads", [])],
                      "sql": cat.get("view_definition", "")})
        if "history_of" in info:
            edges.append([table, info["history_of"], "history"])
        audit = info.get("audit", "")   # the audit column a model declares; drawn faintly, never as a business edge
        for c, target in fks.items():
            tt = target.rsplit(".", 1)[0]
            if tt in cats and c != audit:
                edges.append([table, tt, "fk:" + c])
            elif tt in cats:
                edges.append([table, tt, "audit-fk"])
        for r in cat.get("view_reads", []):
            tt = "%s.%s" % (r["ref_schema"], r["ref_table"])
            if tt in cats:
                edges.append([table, tt, "reads"])

    vault = [x for x in nodes if x["layer"] == "vault"]
    degree = {}
    for x, y, k in edges:
        degree[x] = degree.get(x, 0) + 1
        degree[y] = degree.get(y, 0) + 1
    source_nodes = [x["id"] for x in nodes if x["layer"] == "source" and x["kind"] in ("table", "view")]
    ranked = sorted(source_nodes, key=lambda i: (-degree.get(i, 0), i))
    title = args.title or ("Raw source: " + ", ".join(args.source) if args.source else "WWI schema")
    start = "hub_sales_order" if any(x["id"] == "hub_sales_order" for x in vault) else (ranked[0] if ranked else None)
    data = {"nodes": nodes, "edges": edges, "title": title, "start": start, "starts": ranked[:5],
            "has_vault": bool(vault),
            "built": {"hubs": len(hubs), "links": len(links), "satellites": len(sats), "references": len(refs),
                      "generated": sum(1 for x in nodes if x.get("gen")), "source_tables": len(cats)}}
    with open(os.path.join(HERE, "template.html"), encoding="utf-8") as f:
        tpl = f.read()
    frag = tpl.replace("/*__DATA__*/null", json.dumps(data, ensure_ascii=False, separators=(",", ":")))
    if args.source:
        frag = frag.replace("<title>WWI Schema Viewer</title>", "<title>%s</title>" % title.replace("<", "&lt;"), 1)
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "fragment.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(frag)
    full = ("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, viewport-fit=cover\">\n"
            "</head>\n<body>\n" + frag + "\n</body>\n</html>\n")
    with open(os.path.join(args.out, "schema_viewer.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(full)
    print("viewer: %d nodes (%d vault, %d source), %d edges" % (
        len(nodes), sum(1 for x in nodes if x["layer"] == "vault"), sum(1 for x in nodes if x["layer"] == "source"),
        len(edges)))


if __name__ == "__main__":
    main()
